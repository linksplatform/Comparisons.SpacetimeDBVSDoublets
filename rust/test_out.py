def write(path, content):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return path


class ParseResultsTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.path = write(os.path.join(self.tmp.name, "out.txt"), SAMPLE_OUT_TXT)

    def test_parses_every_operation_and_variant(self):
        results = out.parse_results(self.path)

        self.assertEqual(len(results), len(out.OPERATIONS))
        for operation, _label in out.OPERATIONS:
            measured = results[operation]
            self.assertEqual(
                sorted(measured),
                sorted(key for key, _label, _color in out.VARIANTS),
                f"missing variants for {operation}",
            )

    def test_parses_thousand_separators(self):
        results = out.parse_results(self.path)

        self.assertEqual(results["create"]["SpacetimeDB"], 3_159_452_615)
        self.assertEqual(results["create"]["Doublets_United_Volatile"], 84_823)

    def test_missing_file_yields_empty_results(self):
        results = out.parse_results(os.path.join(self.tmp.name, "absent.txt"))

        self.assertFalse(out.has_any_results(results))

    def test_unrelated_lines_are_ignored(self):
        path = write(
            os.path.join(self.tmp.name, "noise.txt"),
            "Benchmarking create/SpacetimeDB/1000: Warming up for 3.0000 s\n",
        )

        self.assertFalse(out.has_any_results(out.parse_results(path)))


