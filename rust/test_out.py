class ResultsTableTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        path = write(os.path.join(self.tmp.name, "out.txt"), SAMPLE_OUT_TXT)
        self.results = out.parse_results(path)
        self.table = out.format_results_table(self.results)

    def test_table_has_a_row_per_operation(self):
        rows = [line for line in self.table.splitlines() if line.startswith("|")]

        # header + separator + one row per operation
        self.assertEqual(len(rows), len(out.OPERATIONS) + 2)

    def test_header_lists_every_variant(self):
        header = self.table.splitlines()[0]

        for _key, label, _color in out.VARIANTS:
            self.assertIn(label, header)

    def test_doublets_cells_are_annotated_with_speedup(self):
        create_row = next(
            line for line in self.table.splitlines() if line.startswith("| Create")
        )

        # 3_159_452_615 / 84_823 = 37,247.6x
        self.assertIn("84823 (37247.6x faster)", create_row)
        self.assertIn("3159452615", create_row)

    def test_missing_measurements_render_as_not_available(self):
        partial = {operation: {} for operation, _label in out.OPERATIONS}
        partial["create"]["SpacetimeDB"] = 1000

        table = out.format_results_table(partial)
        create_row = next(
            line for line in table.splitlines() if line.startswith("| Create")
        )

        self.assertIn("N/A", create_row)


class ProvenanceTests(unittest.TestCase):
    def test_local_run_provenance(self):
        provenance = out.build_provenance(
            benchmark_links="1000",
            background_links="3000",
            generated_at="2026-01-01 00:00 UTC",
        )

        self.assertIn("2026-01-01 00:00 UTC", provenance)
        self.assertIn("1000 benchmarked links", provenance)
        self.assertIn("3000 background links", provenance)

    def test_github_actions_provenance_links_to_the_run(self):
        os.environ["GITHUB_REPOSITORY"] = "linksplatform/Comparisons.SpacetimeDBVSDoublets"
        os.environ["GITHUB_RUN_ID"] = "1234567890"
        self.addCleanup(os.environ.pop, "GITHUB_REPOSITORY", None)
        self.addCleanup(os.environ.pop, "GITHUB_RUN_ID", None)

        provenance = out.build_provenance(generated_at="2026-01-01 00:00 UTC")

        self.assertIn(
            "https://github.com/linksplatform/Comparisons.SpacetimeDBVSDoublets"
            "/actions/runs/1234567890",
            provenance,
        )


class ReadmeUpdateTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.readme = write(os.path.join(self.tmp.name, "README.md"), README_TEMPLATE)

    def read(self):
        with open(self.readme, "r", encoding="utf-8") as handle:
            return handle.read()

    def test_replaces_content_between_markers(self):
        self.assertTrue(out.update_readme(self.readme, "TABLE"))

        content = self.read()
        self.assertIn(f"{out.README_START_MARKER}\nTABLE\n{out.README_END_MARKER}", content)
        self.assertNotIn("will be generated by CI", content)
        self.assertIn("## Conclusion", content)

    def test_update_is_idempotent(self):
        out.update_readme(self.readme, "TABLE")

        self.assertFalse(out.update_readme(self.readme, "TABLE"))

    def test_special_regex_characters_survive_replacement(self):
        section = r"| Create | 100 (1.5x faster) \g<0> $1 |"

        out.update_readme(self.readme, section)

        self.assertIn(section, self.read())

    def test_missing_markers_raise(self):
        path = write(os.path.join(self.tmp.name, "no-markers.md"), "# Title\n")

        with self.assertRaises(ValueError):
            out.update_readme(path, "TABLE")


class MainTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.input = write(os.path.join(self.tmp.name, "out.txt"), SAMPLE_OUT_TXT)
        self.readme = write(os.path.join(self.tmp.name, "README.md"), README_TEMPLATE)
        self.results = os.path.join(self.tmp.name, "results.md")
        self.docs = os.path.join(self.tmp.name, "Docs")

    def test_writes_results_and_updates_readme(self):
        exit_code = out.main(
            [
                self.input,
                "--results",
                self.results,
                "--readme",
                self.readme,
                "--output-dir",
                self.tmp.name,
                "--docs-dir",
                self.docs,
            ]
        )

        self.assertEqual(exit_code, 0)
        with open(self.results, "r", encoding="utf-8") as handle:
            results_md = handle.read()
        self.assertIn("| Create", results_md)
        with open(self.readme, "r", encoding="utf-8") as handle:
            self.assertIn("| Create", handle.read())

    @unittest.skipUnless(out.HAS_MATPLOTLIB, "matplotlib is not installed")
    def test_generates_and_copies_charts(self):
        out.main(
            [
                self.input,
                "--results",
                self.results,
                "--output-dir",
                self.tmp.name,
                "--docs-dir",
                self.docs,
            ]
        )

        for chart in ("bench_rust.png", "bench_rust_log_scale.png"):
            self.assertTrue(os.path.exists(os.path.join(self.tmp.name, chart)), chart)
            self.assertTrue(os.path.exists(os.path.join(self.docs, chart)), chart)

    def test_empty_input_reports_failure(self):
        empty = write(os.path.join(self.tmp.name, "empty.txt"), "")

        self.assertEqual(out.main([empty, "--results", self.results]), 1)


if __name__ == "__main__":
    unittest.main()
